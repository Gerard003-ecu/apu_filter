class AtomicInt32:
    """
    Entero alineado de 32 bits con carga, depósito y CAS.

    En CPython el GIL serializa el cuerpo de cada método: el
    compare-exchange es atómico respecto de otros hilos Python. No se
    toma ningún mutex de SO ni se espera. El respaldo ``ctypes.c_int32``
    evita el internado de ``int`` y fija la dirección de memoria.
    """

    __slots__ = ("_cell",)

    def __init__(self, initial: int = 0) -> None:
        self._cell = ctypes.c_int32(int(initial))

    def load_acquire(self) -> int:
        return int(self._cell.value)

    def store_release(self, value: int) -> None:
        self._cell.value = int(value)

    def compare_exchange(self, expected: int, desired: int) -> Tuple[bool, int]:
        current = int(self._cell.value)
        if current == int(expected):
            self._cell.value = int(desired)
            return True, current
        return False, current

    def fetch_or(self, mask: int) -> int:
        """Publica bits y devuelve el valor *previo* (un disparo, sin espera)."""
        current = int(self._cell.value)
        self._cell.value = int(current | int(mask))
        return current


@dataclass(frozen=True, slots=True)
class LatchSnapshot:
    """Instantánea inmutable del cerrojo fail-secure."""

    latched: bool
    generation: int
    cas_succeeded: bool
    host_cas_ns: float
    model_latency_ns: float
    within_model_bound: bool


class FailSecureLatch:
    r"""
    Cerrojo de un bit + generación, protocolo release/acquire.

    * ``trip()``  — CAS/fetch_or \(0\to 1\), incrementa generación, no espera.
    * ``is_latched()`` — load-acquire, \(\mathcal{O}(1)\), nunca bloquea.
    * ``try_reset()`` — CAS \(1\to 0\) reservado al laboratorio.

    La cota ``_INTERLOCK_LATENCY_NS`` es el SLO del *modelo* de perímetro.
    El tiempo de huésped se reporta aparte: Python no cabe en 400 ns y
    pretenderlo generaría un falso degradado.
    """

    __slots__ = ("_flag", "_generation")

    def __init__(self) -> None:
        self._flag = AtomicInt32(_LATCH_OPEN)
        self._generation = AtomicInt32(0)

    def is_latched(self) -> bool:
        return self._flag.load_acquire() != _LATCH_OPEN

    def generation(self) -> int:
        return self._generation.load_acquire()

    def trip(self) -> LatchSnapshot:
        started = time.perf_counter_ns()
        previous = self._flag.fetch_or(_LATCH_CLOSED)
        succeeded = previous == _LATCH_OPEN
        if succeeded:
            self._generation.store_release(self._generation.load_acquire() + 1)
        host_ns = float(max(0, time.perf_counter_ns() - started))
        return LatchSnapshot(
            latched=True,
            generation=self._generation.load_acquire(),
            cas_succeeded=bool(succeeded),
            host_cas_ns=host_ns,
            model_latency_ns=_INTERLOCK_LATENCY_NS,
            within_model_bound=True,
        )

    def snapshot(self) -> LatchSnapshot:
        return LatchSnapshot(
            latched=self.is_latched(),
            generation=self.generation(),
            cas_succeeded=True,
            host_cas_ns=0.0,
            model_latency_ns=0.0 if not self.is_latched() else _INTERLOCK_LATENCY_NS,
            within_model_bound=True,
        )

    def try_reset(self) -> bool:
        ok, _ = self._flag.compare_exchange(_LATCH_CLOSED, _LATCH_OPEN)
        if ok:
            self._generation.store_release(self._generation.load_acquire() + 1)
        return bool(ok)


