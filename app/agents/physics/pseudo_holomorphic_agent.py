# SUTURA I — ARITMÉTICA COMPENSADA (TwoSum / TwoProd / KBN / Dot2 / Higham)
# ═══════════════════════════════════════════════════════════════════════════════
def _two_sum(left: float, right: float) -> Tuple[float, float]:
    """Knuth TwoSum: \(s+e=a+b\) exactamente en \(\mathbb{F}\) (sin overflow)."""
    total = left + right
    rounded = total - left
    err = (left - (total - rounded)) + (right - rounded)
    return float(total), float(err)


def _fast_two_sum(large: float, small: float) -> Tuple[float, float]:
    """Dekker FastTwoSum; exige \(\lvert\mathrm{large}\rvert\ge\lvert\mathrm{small}\rvert\)."""
    total = large + small
    err = small - (total - large)
    return float(total), float(err)


def _two_prod(left: float, right: float) -> Tuple[float, float]:
    r"""
    TwoProd exacto vía FMA: \(p=\mathrm{fl}(ab)\), \(e=\mathrm{fma}(a,b,-p)\),
    de modo que \(p+e=ab\) en \(\mathbb{R}\) (salvo overflow).
    """
    prod = left * right
    err = math.fma(left, right, -prod)
    return float(prod), float(err)


def higham_gamma(length: int, unit_roundoff: float = _MACHINE_EPS) -> float:
    r"""
    Constante de Higham \(\gamma_k=ku/(1-ku)\) para productos internos de
    longitud \(k\). Si \(ku\ge 1\) el modelo deja de ser válido y se
    devuelve \(+\infty\) (toda comparación debe degradar, no vetar).
    """
    steps = max(0, int(length))
    if steps == 0:
        return 0.0
    ku = steps * float(unit_roundoff)
    if not math.isfinite(ku) or ku >= 1.0:
        return float("inf")
    return float(ku / (1.0 - ku))


def kbn_sum(values: Sequence[float]) -> Tuple[float, float]:
    r"""
    Suma de Kahan–Babuška–Neumaier.

    A diferencia del Kahan clásico, KBN no exige \(\lvert s\rvert\ge\lvert x\rvert\)
    y permanece fiel cuando los sumandos cambian de signo y de magnitud.
    Devuelve \((\hat s,\,c)\) con \(\hat s+c\) igual a la suma compensada y
    \(c\) el residuo de compensación (diagnóstico de deriva FPU).
    """
    total = 0.0
    compensation = 0.0
    for raw in values:
        term = float(raw)
        if term == 0.0:
            continue
        tentative = total + term
        if abs(total) >= abs(term):
            compensation += (total - tentative) + term
        else:
            compensation += (term - tentative) + total
        total = tentative
    return float(total), float(compensation)


def compensated_sum_of_squares(values: Sequence[float]) -> Tuple[float, float]:
    r"""
    \(\sum x_i^2\) con TwoProd (cuadrado exacto) + KBN (suma fiel).

    Devuelve \((\widehat{\sum x^2},\,c_{\mathrm{KBN}}+\sum e_{\mathrm{TwoProd}})\).
    """
    total = 0.0
    compensation = 0.0
    product_tail = 0.0
    for raw in values:
        term = float(raw)
        if term == 0.0:
            continue
        square, square_err = _two_prod(term, term)
        product_tail += square_err
        tentative = total + square
        if abs(total) >= abs(square):
            compensation += (total - tentative) + square
        else:
            compensation += (square - tentative) + total
        total = tentative
    return float(total), float(compensation + product_tail)


def frobenius_kbn(matrix: np.ndarray) -> Tuple[float, float]:
    r"""
    Norma de Frobenius compensada, con escala para evitar overflow:

    \[
      \|A\|_F
      =\sigma\sqrt{\sum(a_{ij}/\sigma)^2},
      \qquad\sigma=\|A\|_\infty.
    \]
    """
    if matrix.size == 0:
        return 0.0, 0.0
    flat = np.ascontiguousarray(matrix, dtype=np.float64).ravel()
    scale = float(np.max(np.abs(flat)))
    if scale == 0.0:
        return 0.0, 0.0
    if not math.isfinite(scale):
        raise FpuMetrologyError("‖A‖_∞ no es finita: la norma de Frobenius es ilegible.")
    scaled = flat / scale
    sumsq, tail = compensated_sum_of_squares(scaled.tolist())
    total, extra = _two_sum(sumsq, tail)
    if total < 0.0 and total > -1e-15:
        total = 0.0
    if total < 0.0:
        raise FpuMetrologyError("Suma de cuadrados negativa tras compensación KBN.")
    norm = scale * math.sqrt(total)
    # Diagnóstico: contribución relativa de la cola de compensación.
    correction = abs(extra) * (scale * scale) / max(total * scale * scale, _MACHINE_EPS)
    return float(norm), float(correction)


def dot2(left: np.ndarray, right: np.ndarray) -> float:
    r"""
    Producto interno fiel Dot2 de Ogita–Rump–Oishi (2005):

    \[
      \mathrm{fl}_{\mathrm{Dot2}}(x^\top y)
      \;=\; x^\top y + \theta,\qquad
      \lvert\theta\rvert\le\gamma_n^2\lvert x\rvert^\top\lvert y\rvert.
    \]
    """
    if left.size != right.size:
        raise FpuMetrologyError("Dot2 exige vectores de la misma longitud.")
    if left.size == 0:
        return 0.0
    x_vec = np.ascontiguousarray(left, dtype=np.float64).ravel()
    y_vec = np.ascontiguousarray(right, dtype=np.float64).ravel()
    prod, err = _two_prod(float(x_vec[0]), float(y_vec[0]))
    total = prod
    compensation = err
    for idx in range(1, x_vec.size):
        prod, prod_err = _two_prod(float(x_vec[idx]), float(y_vec[idx]))
        total, sum_err = _two_sum(total, prod)
        compensation += sum_err + prod_err
    result, _ = _two_sum(total, compensation)
    return float(result)


def _dot2_matmul(left: np.ndarray, right: np.ndarray) -> np.ndarray:
    """GEMM fiel \(C_{ij}=\mathrm{Dot2}(A_{i,:},B_{:,j})\) para bloques pequeños."""
    rows, mid = left.shape
    mid_r, cols = right.shape
    if mid != mid_r:
        raise FpuMetrologyError("Dimensiones incompatibles en Dot2-GEMM.")
    out = np.empty((rows, cols), dtype=np.float64)
    for i in range(rows):
        row = left[i, :]
        for j in range(cols):
            out[i, j] = dot2(row, right[:, j])
    return out


