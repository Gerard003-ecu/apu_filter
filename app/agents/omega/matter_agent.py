    def __init__(
        self,
        engine: Optional[MatterGenerator] = None,
        max_gini_critical: float = 0.85,
        max_exergy_friction: float = 1e6,
        rayleigh_exponent: float = _RAYLEIGH_EXPONENT,
        rayleigh_viscosity: float = _RAYLEIGH_VISCOSITY_COEFFICIENT,
    ) -> None:
        try:
            super().__init__(name="MatterAgent")
        except TypeError:
            super().__init__()

        # ── Fase 1: Validación de Parámetros y Calibración RSI-L3 ─────────────
        self._phase1 = MatterAgent.Phase1_ParameterValidation(
            engine=engine,
            max_gini_critical=max_gini_critical,
            max_exergy_friction=max_exergy_friction,
            rayleigh_exponent=rayleigh_exponent,
            rayleigh_viscosity=rayleigh_viscosity,
        )
        # Continuación Formal Fase 1 ──► Fase 2 vía build_context()
        self._context: MatterAgentContext = self._phase1.build_context()

        # ── Fase 2: Deliberación Termodinámica, Fermi y Poincaré ──────────────
        self._phase2 = MatterAgent.Phase2_ThermodynamicDeliberation(
            context=self._context
        )

        # ── Fase 3: Proyección Categórica y Homología Simplicial ──────────────
        self._phase3 = MatterAgent.Phase3_CategoricalProjection(
            context=self._context
        )

        self._last_verdict: Optional[HadronicDeliberationVerdict] = None

        logger.info(
            "MatterAgent v%s inicializado | context_hash=%s",
            MODULE_VERSION,
            self._context.context_hash,
        )

    @property
    def context(self) -> MatterAgentContext:
        """Contexto inmutable sellado en la Fase 1 (solo lectura)."""
        return self._context

    def rsi_level3_telemetry(self) -> RSILevel3MatterTelemetry:
        """Retorna el certificado epistémico de Automejora Recursiva de Nivel 3."""
        v = self._last_verdict
        return RSILevel3MatterTelemetry(
            banach_reconciliation_iters=self._context.rsi_l3_reconciliation_iters,
            banach_contraction_residual=0.0,
            chandrasekhar_mass_limit_calibrated=self._context.chandrasekhar_mass_limit,
            fermi_pauli_stabilization_active=(
                v.rsi_l3_damping_applied if v is not None else False
            ),
            fermi_pressure_injected_Pa=(
                v.fermi_degeneracy_pressure if v is not None else 0.0
            ),
            poincare_kam_stability_index=self._context.poincare_kam_margin,
            betti_numbers=self._phase3._last_betti,
            hodge_spectral_gap=self._phase3._last_hodge_gap,
        )

    def project_intent_and_deliberate(
        self,
        hierarchical_complex: Any,
        root_node: str,
        friction_map: Dict[str, float],
        price_map: Dict[str, float],
    ) -> CategoricalState:
        r"""
        Interfaz externa principal del endofuntor :math:`F = \pi \circ \delta \circ \varphi`.

        Orquesta la composición completa de las tres fases anidadas:

        1. **φ (Motor Físico)**: Proyecta el complejo jerárquico en un ``BillOfMaterials``.
        2. **δ (Fase 2)**: Aplica los vetos termodinámicos/relativistas y calcula
           el tensor :math:`T_{\mu\nu}`, la presión de Fermi y el virial de Poincaré.
        3. **π (Fase 3)**: Calcula la homología de Euler-Poincaré y proyecta el
           veredicto en un ``CategoricalState`` del estrato ``WISDOM``.
        """
        ts_total: float = time.perf_counter()

        logger.info(
            "Iniciando colapso hadrónico en el Estrato Ω | "
            "root='%s' | ctx_hash=%s",
            root_node,
            self._context.context_hash[:16],
        )

        # ── Paso 1: φ – Motor físico (Estrato TACTICS/PHYSICS) ───────────────
        bom_tensor: BillOfMaterials = self._context.engine.project_to_bom(
            hierarchical_complex=hierarchical_complex,
            root_node=root_node,
            friction_tensor_map=friction_map,
            price_tensor_map=price_map,
        )

        # ── Paso 2: δ – Deliberación Termodinámica y Celeste (Fase 2) ────────
        verdict: HadronicDeliberationVerdict = self._phase2.deliberate(
            bom_tensor
        )
        self._last_verdict = verdict

        # ── Paso 3: π – Proyección Categórica y Homológica (Fase 3) ──────────
        final_state: CategoricalState = self._phase3.project(verdict)

        elapsed: float = time.perf_counter() - ts_total

        logger.info(
            "Colapso hadrónico completado | isomorfismo de masa preservado | "
            "stratum=%s | elapsed=%.4fs",
            final_state.stratum,
            elapsed,
        )

        return final_state

    def forward(self, state: CategoricalState) -> CategoricalState:
        r"""
        Implementación del contrato categórico ``Morphism.forward``.

        Si el ``payload`` de ``state`` contiene un ``BillOfMaterials`` bajo la
        clave ``"bom_tensor"`` (o es directamente un ``BillOfMaterials``),
        ejecuta la cadena :math:`\pi \circ \delta`; si contiene los argumentos
        de ``project_intent_and_deliberate``, ejecuta :math:`\pi \circ \delta \circ \varphi`.
        """
        payload = getattr(state, "payload", None)
        if isinstance(payload, BillOfMaterials):
            verdict = self._phase2.deliberate(payload)
            self._last_verdict = verdict
            return self._phase3.project(verdict)

        if isinstance(payload, dict):
            if "bom_tensor" in payload and isinstance(
                payload["bom_tensor"], BillOfMaterials
            ):
                verdict = self._phase2.deliberate(payload["bom_tensor"])
                self._last_verdict = verdict
                return self._phase3.project(verdict)

            if "hierarchical_complex" in payload and "root_node" in payload:
                return self.project_intent_and_deliberate(
                    hierarchical_complex=payload["hierarchical_complex"],
                    root_node=str(payload["root_node"]),
                    friction_map=dict(payload.get("friction_map", {})),
                    price_map=dict(payload.get("price_map", {})),
                )

        raise TypeError(
            "MatterAgent.forward requiere un CategoricalState con 'bom_tensor' "
            "o con ('hierarchical_complex', 'root_node', 'friction_map', 'price_map')."
        )

    def backward(self, state: CategoricalState) -> CategoricalState:
        """Retracción adjunta del morfismo en el Topos MIC."""
        return self.forward(state)


