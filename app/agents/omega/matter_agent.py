    class Phase3_CategoricalProjection:
        r"""
        **FASE 3 ANIDADA: Homología Simplicial de Hodge-Poincaré, Invariante
        Integral de Poincaré-Cartan y Proyección Categórica al Topos MIC.**

        Continuación formal desde la Fase 2
        -----------------------------------
        El primer método de esta fase, ``_ingest_phase2_verdict``, recibe y
        verifica el ``HadronicDeliberationVerdict`` emitido por el método
        terminal ``Phase2_ThermodynamicDeliberation.deliberate()``.

        Clausura Funtorial
        ------------------
        El método terminal ``project()`` sella el morfismo compuesto
        :math:`F = \pi \circ \delta \circ \varphi` entregando un ``CategoricalState``
        en el estrato ``Stratum.WISDOM``.
        """

        def __init__(self, context: MatterAgentContext) -> None:
            self._ctx = context
            self._last_betti: Tuple[int, int, int] = (1, 0, 0)
            self._last_hodge_gap: float = 0.0

        @staticmethod
        def _ingest_phase2_verdict(
            verdict: HadronicDeliberationVerdict,
        ) -> HadronicDeliberationVerdict:
            r"""
            3.1 **MÉTODO INICIAL DE LA FASE 3 (Continuación Formal de la Fase 2).**

            Valida el contrato de integridad del ``HadronicDeliberationVerdict``
            producido por ``Phase2_ThermodynamicDeliberation.deliberate()``.
            """
            if not isinstance(verdict, HadronicDeliberationVerdict):
                raise TypeError(
                    f"[Fase3] Se esperaba HadronicDeliberationVerdict de Fase 2; "
                    f"se recibió {type(verdict).__name__}."
                )
            if not verdict.is_viable:
                raise HadronicCollapseVetoError(
                    reason=(
                        f"[Fase3] Intento de proyectar un veredicto no viable: "
                        f"{verdict.topological_veto_reason}"
                    )
                )
            if not verdict.morphism_signature:
                raise ValueError(
                    "[Fase3] HadronicDeliberationVerdict carece de morphism_signature."
                )
            return verdict

        @staticmethod
        def _compute_hodge_betti_and_spectral_gap(
            bom: BillOfMaterials,
        ) -> Tuple[Tuple[int, int, int], float]:
            r"""
            3.2 Calcula los números de Betti :math:`(\beta_0, \beta_1, \beta_2)` y el
            gap espectral de Fiedler-Hodge :math:`\lambda_2(\Delta_0)` del complejo
            simplicial :math:`K` asociado al BOM.

            Si el BOM expone una matriz de adyacencia ``adjacency_matrix``, se
            diagonaliza el Laplaciano de Hodge de 0-formas :math:`\Delta_0 = D - A`:

            .. math::

                \beta_0 = \dim \ker(\Delta_0), \qquad
                \beta_1 = E - V + \beta_0 - F.
            """
            if hasattr(bom, "adjacency_matrix") and getattr(bom, "adjacency_matrix") is not None:
                A = np.asarray( getattr(bom, "adjacency_matrix"), dtype=np.float64)
                if A.ndim == 2 and A.shape[0] == A.shape[1] and A.shape[0] > 0:
                    A_sym = 0.5 * (np.abs(A) + np.abs(A.T))
                    np.fill_diagonal(A_sym, 0.0)
                    A_bin = (A_sym > _FLOAT_EPSILON).astype(np.float64)
                    V = int(A_bin.shape[0])
                    E = int(np.sum(A_bin) // 2)
                    degrees = np.sum(A_bin, axis=1)
                    L0 = np.diag(degrees) - A_bin
                    eigvals = np.linalg.eigvalsh(L0)
                    beta_0 = int(np.sum(np.abs(eigvals) <= 1.0e-9))
                    positive_eigs = eigvals[eigvals > 1.0e-9]
                    spectral_gap = float(positive_eigs[0]) if positive_eigs.size > 0 else 0.0
                    # Número de 2-símplices (triángulos cerrados)
                    triangles = int(np.trace(A_bin @ A_bin @ A_bin) // 6)
                    beta_1 = max(E - V + beta_0 - triangles, 0)
                    return (max(beta_0, 1), beta_1, 0), spectral_gap

            if hasattr(bom, "num_nodes") and hasattr(bom, "num_edges"):
                V = max(int(bom.num_nodes), 1)
                E = max(int(bom.num_edges), 0)
                beta_0 = 1
                # Para complejo planar conexo con cara exterior: χ = V - E + 1
                # expresado en Betti efectivos: β_0 - β_1 + β_2 = V - E + 1
                cyclomatic = max(E - V + 1, 0)
                spectral_gap = 2.0 * (1.0 - math.cos(math.pi / max(V, 2)))
                return (beta_0, cyclomatic, 1 if E >= V else 0), float(spectral_gap)

            return (1, 0, 0), 1.0

        @staticmethod
        def _compute_euler_poincare(bom: BillOfMaterials) -> int:
            r"""
            3.3 Calcula la Característica de Euler-Poincaré :math:`\chi(K)` del
            complejo simplicial logístico :math:`K`:

            .. math::

                \chi(K) = \sum_{k \ge 0} (-1)^k \beta_k = V - E + F.

            Orden de prioridad estricto:
            1. ``bom.euler_characteristic`` (si el motor físico provee topología exacta).
            2. ``bom.num_nodes`` y ``bom.num_edges`` (:math:`\chi = V - E + 1`).
            3. Fallback canónico: :math:`\chi = 1` (complejo contractible).
            """
            if hasattr(bom, "euler_characteristic"):
                chi = int(bom.euler_characteristic)
                logger.debug("χ(K) = %d (provisto por motor físico).", chi)
                return chi

            if hasattr(bom, "num_nodes") and hasattr(bom, "num_edges"):
                V: int = int(bom.num_nodes)
                E: int = int(bom.num_edges)
                chi = V - E + 1
                logger.debug(
                    "χ(K) = V - E + 1 = %d - %d + 1 = %d (topología de grafo).",
                    V,
                    E,
                    chi,
                )
                return chi

            logger.debug("χ(K) = 1 (fallback: complejo contractible).")
            return 1

        @staticmethod
        def _compute_poincare_cartan_invariant(
            verdict: HadronicDeliberationVerdict, chi: int
        ) -> float:
            r"""
            3.4 Primer Invariante Integral Relativo de Poincaré-Cartan sobre el
            espacio de fases termodinámico-logístico:

            .. math::

                \mathcal{I}_{\mathrm{Poincaré}}
                  = \oint_{\gamma \subset K} \bigl(p_\mu\,dq^\mu - H\,dt\bigr)
                  \approx \frac{E_x(\mathrm{BOM}) \cdot (1 - G(\mathrm{BOM}))}{1 + |\chi(K)|}.
            """
            exergy = max(float(verdict.exergy_available), 0.0)
            ergodic_factor = max(1.0 - float(verdict.gini_asymmetry), 0.0)
            topo_weight = 1.0 + float(abs(chi))
            return float((exergy * ergodic_factor) / topo_weight)

        def _compute_projection_signature(
            self, verdict: HadronicDeliberationVerdict
        ) -> str:
            r"""
            3.5 Calcula la firma SHA-256 de la proyección :math:`\pi`, enlazando
            ``verdict.morphism_signature`` con ``context.context_hash``.
            """
            composite: str = json.dumps(
                {
                    "phi_sig": verdict.morphism_signature,
                    "ctx_hash": self._ctx.context_hash,
                    "gini": f"{verdict.gini_asymmetry:.12f}",
                    "exergy_d": f"{verdict.exergy_dissipated:.12f}",
                    "exergy_a": f"{verdict.exergy_available:.12f}",
                    "ts": f"{verdict.deliberation_timestamp_utc:.6f}",
                },
                sort_keys=True,
                separators=(",", ":"),
            )
            return hashlib.sha256(composite.encode("utf-8")).hexdigest()

        def project(
            self, verdict: HadronicDeliberationVerdict
        ) -> CategoricalState:
            r"""
            3.6 **MÉTODO TERMINAL DE LA FASE 3 (Clausura del Endofuntor $F = \pi \circ \delta \circ \varphi$).**

            Ingiere formalmente el ``HadronicDeliberationVerdict`` de la Fase 2,
            calcula los invariantes homológicos de Euler-Poincaré y de Hodge,
            evalúa la acción simpléctica de Poincaré-Cartan y proyecta el resultado
            en un ``CategoricalState`` del estrato ``Stratum.WISDOM``.
            """
            verdict = self._ingest_phase2_verdict(verdict)

            # Paso 1: Invariantes topológicos (Euler-Poincaré y Betti de Hodge)
            chi: int = self._compute_euler_poincare(verdict.bom_tensor)
            betti, hodge_gap = self._compute_hodge_betti_and_spectral_gap(
                verdict.bom_tensor
            )
            self._last_betti = betti
            self._last_hodge_gap = hodge_gap

            # Paso 2: Invariante integral de Poincaré-Cartan
            poincare_action: float = self._compute_poincare_cartan_invariant(
                verdict, chi
            )

            # Paso 3: Firma criptográfica de la composición completa F = π ∘ δ ∘ φ
            pi_sig: str = self._compute_projection_signature(verdict)

            logger.info(
                "Fase 3 completada | χ(K)=%d | Betti=%s | I_Poincaré=%.4f | "
                "π-sig=%s | viable=%s",
                chi,
                betti,
                poincare_action,
                pi_sig[:16],
                verdict.is_viable,
            )

            se_dict = (
                verdict.stress_energy_metrics.to_dict()
                if verdict.stress_energy_metrics is not None
                else {}
            )

            # ── RESULTADO TERMINAL DEL ENDOFUNTOR SOBERANO F ──────────────────
            return CategoricalState(
                stratum=Stratum.WISDOM,
                payload={
                    # Tensor de materiales original
                    "bom_tensor": verdict.bom_tensor,

                    # Métricas completas de deliberación termodinámica y relativista
                    "deliberation_metrics": {
                        "gini_asymmetry": verdict.gini_asymmetry,
                        "exergy_dissipated_W": verdict.exergy_dissipated,
                        "exergy_available_J": verdict.exergy_available,
                        "fermi_degeneracy_pressure_Pa": verdict.fermi_degeneracy_pressure,
                        "poincare_virial_index": verdict.poincare_virial_index,
                        "rsi_l3_damping_applied": verdict.rsi_l3_damping_applied,
                        "is_viable": verdict.is_viable,
                        "veto_reason": verdict.topological_veto_reason,
                        "deliberation_ts_utc": verdict.deliberation_timestamp_utc,
                        "stress_energy_tensor": se_dict,
                    },

                    # Invariantes topológicos y simplécticos del complejo logístico
                    "topological_invariants": {
                        "euler_poincare_characteristic": chi,
                        "betti_numbers": betti,
                        "hodge_laplacian_spectral_gap": hodge_gap,
                        "poincare_cartan_integral_invariant": poincare_action,
                    },

                    # Trazabilidad criptográfica de la composición F = π ∘ δ ∘ φ
                    "morphism_chain": {
                        "phi_signature": verdict.morphism_signature,
                        "pi_signature": pi_sig,
                        "context_hash": self._ctx.context_hash,
                        "module_version": MODULE_VERSION,
                    },
                },
            )

