    def generate_fock_session_signature(
        self,
        boundary_matrix: np.ndarray,
        Choi_matrix: np.ndarray,
        bell_correlations: Tuple[float, float, float, float],
        payload: bytes,
    ) -> str:
        """
        API compatible con la versión original.

        Genera firma de sesión canónica con separación de dominio.
        """
        payload_b = self._phase1_validate_payload(payload)
        bell = self._phase1_canonical_bell(bell_correlations)

        B = np.ascontiguousarray(np.asarray(boundary_matrix))
        try:
            C, _resid = self._phase1_canonical_choi(Choi_matrix)
        except ValueError:
            C = np.ascontiguousarray(np.asarray(Choi_matrix))

        sha = hashlib.sha256()

        self._hash_update_domain(sha, _DOMAIN_SESSION)
        self._hash_update_array(sha, "boundary_matrix", B)
        self._hash_update_array(sha, "Choi_matrix", C)

        bell_arr = np.ascontiguousarray(np.asarray(bell, dtype=np.float64))
        self._hash_update_bytes(sha, bell_arr.tobytes(order="C"))

        self._hash_update_bytes(sha, payload_b)

        return sha.hexdigest()

    def execute_boundary_sovereign_cycle(
        self,
        payload: bytes,
        K_boundary_raw: np.ndarray,
        metric_tensor: np.ndarray,
        boundary_matrix_integer: np.ndarray,
        Choi_matrix: np.ndarray,
        bell_correlations: Tuple[float, float, float, float],
        reference_entropy_threshold: float = 1.5,
        euler_characteristic: int = 1,
    ) -> BoundaryRingSheafAgentCertificate:
        """
        Punto de entrada público del ciclo OODA completo.

        Ejecuta la cadena anidada:

            FASE 1 · OBSERVE
              └─ FASE 2 · ORIENT / DECIDE
                   └─ FASE 3 · ACT / CERTIFY

        Si ocurre cualquier excepción, devuelve certificado fail-closed VETOED.
        """
        try:
            return self._phase1_observe_and_freeze(
                payload=payload,
                K_boundary_raw=K_boundary_raw,
                metric_tensor=metric_tensor,
                boundary_matrix_integer=boundary_matrix_integer,
                Choi_matrix=Choi_matrix,
                bell_correlations=bell_correlations,
                reference_entropy_threshold=reference_entropy_threshold,
                euler_characteristic=euler_characteristic,
            )
        except Exception as exc:
            logger.exception(
                "Fallo fail-closed en ciclo soberano; se emite VETO de frontera."
            )
            return self._fail_closed_certificate(payload, reason=str(exc))


