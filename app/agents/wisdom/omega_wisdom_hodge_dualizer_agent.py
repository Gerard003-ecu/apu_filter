class Phase2_ModularOrienter(Phase1_SpectralObserver):
    """
    FASE 2: Construye físicamente el operador modular $J_\rho$ desde el
    espectro de ρ (en vez de asumir un operador externo arbitrario), certifica
    su involución y antiunitariedad GNS de forma numérica (sin stubs), y
    certifica el equilibrio térmico KMS con residuo normalizado por escala.
    
    MEJORAS DOCTORALES v4.0.0:
    ─────────────────────────
    1. Construcción de J_ρ con regularización espectral adaptativa
    2. Clasificación de tipo de álgebra de von Neumann (I, II, III)
    3. Verificación KMS con invariancia de escala Lipschitz
    4. Parámetro de flujo modular explícito (β canónico)
    """
    
    # ═══════════════════════════════════════════════════════════════════════
    # 2.1 CONSTRUCCIÓN FÍSICA DE J_ρ (TOMITA-TAKESAKI)
    # ═══════════════════════════════════════════════════════════════════════
    
    @staticmethod
    def _construct_modular_conjugation_operator(
        rho: ComplexMatrix, 
        floor: float = 1e-12,
        spectral_gap_threshold: float = _SPECTRAL_GAP_FLOOR
    ) -> Tuple[ComplexMatrix, ComplexMatrix, float]:
        r"""
        Construye los factores espectrales $\rho^{1/2}$ y $\rho^{-1/2}$
        (regularizados) requeridos por la conjugación modular:
        $$J_\rho(X) = \rho^{1/2} X^\dagger \rho^{-1/2}$$
        
        MEJORA v4.0.0: 
        - Regularización adaptativa basada en gap espectral
        - Detección de álgebras Tipo III (gap → 0)
        - Retorno del factor de regularización aplicado
        
        Args:
            rho: Matriz de densidad
            floor: Piso de regularización base
            spectral_gap_threshold: Umbral para detectar degeneración espectral
        
        Returns:
            (rho_sqrt, rho_inv_sqrt, regularization_factor)
        
        Raises:
            SpectralGapDegeneracyError: Si el gap espectral es demasiado pequeño
        """
        eigvals, eigvecs = la.eigh(rho)
        
        # MEJORA v4.0.0: Análisis de gap espectral para clasificación de tipo
        eigvals_sorted = np.sort(eigvals)[::-1]
        if len(eigvals_sorted) > 1:
            spectral_gaps = np.diff(eigvals_sorted)
            min_gap = float(np.min(np.abs(spectral_gaps)))
        else:
            min_gap = float('inf')
        
        # MEJORA v4.0.0: Regularización adaptativa
        if min_gap < spectral_gap_threshold:
            logger.warning(
                "Gap espectral pequeño detectado (%.4e) — posible álgebra Tipo III. "
                "Aplicando regularización reforzada.", min_gap
            )
            floor = max(floor, spectral_gap_threshold * 10)
        
        eigvals_reg = np.clip(eigvals, floor, None)
        
        rho_sqrt = eigvecs @ np.diag(np.sqrt(eigvals_reg)) @ eigvecs.conj().T
        rho_inv_sqrt = eigvecs @ np.diag(1.0 / np.sqrt(eigvals_reg)) @ eigvecs.conj().T
        
        regularization_factor = float(np.max(np.abs(eigvals_reg - eigvals)))
        
        return rho_sqrt, rho_inv_sqrt, regularization_factor
    
    @staticmethod
    def _apply_modular_conjugation(
        rho_sqrt: ComplexMatrix, 
        rho_inv_sqrt: ComplexMatrix, 
        x_op: ComplexMatrix
    ) -> ComplexMatrix:
        r"""
        Aplica el superoperador antiunitario $J_\rho(X) = \rho^{1/2}X^\dagger\rho^{-1/2}$.
        
        MEJORA v4.0.0: Verificación de estabilidad numérica intermedia
        """
        x_dagger = x_op.conj().T
        
        # MEJORA v4.0.0: Verificación de finitud antes de multiplicación
        if not np.all(np.isfinite(x_dagger)):
            raise ModularConjugationViolation(
                "Operador de entrada contiene valores no finitos para conjugación modular."
            )
        
        intermediate = rho_sqrt @ x_dagger
        if not np.all(np.isfinite(intermediate)):
            raise ModularConjugationViolation(
                "Producto intermedio ρ^(1/2) X^† contiene valores no finitos."
            )
        
        return intermediate @ rho_inv_sqrt
    
    @staticmethod
    def _gns_inner_product(
        rho: ComplexMatrix, 
        a_op: ComplexMatrix, 
        b_op: ComplexMatrix
    ) -> complex:
        r"""
        Producto interno GNS: $\langle A,B\rangle_\rho = \operatorname{Tr}(\rho A^\dagger B)$.
        
        MEJORA v4.0.0: Simetrización numérica para reducir error de punto flotante
        """
        lhs = rho @ a_op.conj().T @ b_op
        rhs = b_op @ rho @ a_op.conj().T  # Traza cíclica alternativa
        
        # Promediar para reducir error numérico
        trace_val = 0.5 * (np.trace(lhs) + np.trace(rhs))
        return complex(trace_val)
    
    @classmethod
    def _verify_modular_conjugation(
        cls,
        rho: ComplexMatrix,
        a_test: ComplexMatrix,
        b_test: ComplexMatrix,
        j_operator_empirical: Optional[ComplexMatrix] = None,
        tolerance: float = _EPS_MODULAR_INVOLUTION,
        hard_tolerance: float = _HARD_EPS_MODULAR_INVOLUTION,
    ) -> Tuple[bool, float, float, str]:
        r"""
        Certifica físicamente la involución modular $J^2=\mathrm{Id}$ y la
        antiunitariedad GNS $\langle J(A),J(B)\rangle_\rho=\langle B,A\rangle_\rho$,
        construyendo $J_\rho$ directamente del espectro de $\rho$ en lugar de
        asumir un operador externo desacoplado de la física (defecto de v3.0.0).
        
        MEJORA v4.0.0:
        - Clasificación de tipo de álgebra de von Neumann
        - Validación cruzada con operador empírico si está presente
        - Retorno del tipo de álgebra identificado
        
        Returns:
            (is_valid, involution_defect, gns_residual, type_classification)
        """
        rho_sqrt, rho_inv_sqrt, reg_factor = cls._construct_modular_conjugation_operator(rho)
        
        dim = rho.shape[0]
        identity = np.eye(dim, dtype=np.complex128)
        test_operators = [identity, a_test, b_test]
        
        involution_defect = 0.0
        for x_op in test_operators:
            jx = cls._apply_modular_conjugation(rho_sqrt, rho_inv_sqrt, x_op)
            jjx = cls._apply_modular_conjugation(rho_sqrt, rho_inv_sqrt, jx)
            defect = float(la.norm(jjx - x_op, ord="fro")) / math.sqrt(dim)
            involution_defect = max(involution_defect, defect)
        
        # Validación cruzada con operador empírico
        if j_operator_empirical is not None:
            emp_defect = float(la.norm(
                j_operator_empirical @ j_operator_empirical - identity, 
                ord="fro"
            )) / math.sqrt(dim)
            involution_defect = max(involution_defect, emp_defect)
        
        # Verificación de antiunitariedad GNS
        j_a = cls._apply_modular_conjugation(rho_sqrt, rho_inv_sqrt, a_test)
        j_b = cls._apply_modular_conjugation(rho_sqrt, rho_inv_sqrt, b_test)
        
        gns_lhs = cls._gns_inner_product(rho, j_a, j_b)
        gns_rhs = cls._gns_inner_product(rho, b_test, a_test)
        gns_residual = abs(gns_lhs - gns_rhs)
        
        total_defect = max(involution_defect, gns_residual)
        
        # MEJORA v4.0.0: Clasificación de tipo de álgebra
        eigvals = la.eigvalsh(rho)
        min_eigen = float(np.min(eigvals))
        if min_eigen < 1e-10:
            type_classification = "Type_III"  # Álgebra de tipo III (factor singular)
        elif reg_factor > 1e-8:
            type_classification = "Type_II"  # Álgebra de tipo II (trace infinito)
        else:
            type_classification = "Type_I"   # Álgebra de tipo I (matriz finita)
        
        if total_defect <= tolerance:
            return True, involution_defect, gns_residual, type_classification
        
        if total_defect <= hard_tolerance:
            logger.warning(
                "Degradación blanda de la conjugación modular: defecto_involución=%.4e, "
                "residuo_GNS=%.4e, tipo=%s.", 
                involution_defect, gns_residual, type_classification
            )
            return False, involution_defect, gns_residual, type_classification
        
        raise ModularConjugationViolation(
            f"Ruptura catastrófica de la involución modular de Tomita-Takesaki. "
            f"Defecto de involución={involution_defect:.4e}, residuo GNS={gns_residual:.4e} "
            f"> hard_tolerance={hard_tolerance:.4e}."
        )
    
    # ═══════════════════════════════════════════════════════════════════════
    # 2.2 CONDICIÓN KMS (EQUILIBRIO TÉRMICO)
    # ═══════════════════════════════════════════════════════════════════════
    
    @staticmethod
    def _verify_kms_condition_numerical(
        rho: ComplexMatrix,
        a_obs: ComplexMatrix,
        b_obs: ComplexMatrix,
        beta: float = 1.0,
        tolerance: float = _EPS_KMS,
        hard_tolerance: float = _HARD_EPS_KMS,
    ) -> Tuple[bool, float, float]:
        r"""
        Certifica la condición KMS numérica a temperatura inversa canónica
        $\beta$, usando la rotación modular $\sigma_{-i}(A) = \rho^{\beta} A \rho^{-\beta}$
        (regularizada espectralmente contra ρ singular):
        $$\left| \operatorname{Tr}(\rho A B) - \operatorname{Tr}\bigl(\rho B \sigma_{-i}(A)\bigr) \right| \le \tau$$
        
        MEJORA v4.0.0:
        - Parámetro β explícito (temperatura inversa)
        - Residuo normalizado por escala para invariancia Lipschitz
        - Retorno del parámetro de flujo modular aplicado
        
        Returns:
            (is_valid, kms_residual, modular_flow_parameter)
        """
        # Calcular Tr(ρAB)
        trace_ab = float(np.real(np.trace(rho @ a_obs @ b_obs)))
        
        # Descomposición espectral de ρ
        eigvals, eigvecs = la.eigh(rho)
        eigvals_reg = np.clip(eigvals, 1e-12, None)
        
        # Construir ρ^β y ρ^(-β)
        rho_beta = eigvecs @ np.diag(eigvals_reg ** beta) @ eigvecs.conj().T
        rho_inv_beta = eigvecs @ np.diag(eigvals_reg ** (-beta)) @ eigvecs.conj().T
        
        # Calcular σ_{-iβ}(A) = ρ^β A ρ^(-β)
        a_zoomed = rho_beta @ a_obs @ rho_inv_beta
        
        # Calcular Tr(ρ B σ_{-iβ}(A))
        trace_ba_zoomed = float(np.real(np.trace(rho @ b_obs @ a_zoomed)))
        
        raw_residual = abs(trace_ab - trace_ba_zoomed)
        
        # MEJORA v4.0.0: Normalización por escala para invariancia
        scale = max(1.0, float(la.norm(a_obs, ord="fro")) * float(la.norm(b_obs, ord="fro")))
        kms_residual = raw_residual / scale
        
        if kms_residual <= tolerance:
            return True, kms_residual, beta
        
        if kms_residual <= hard_tolerance:
            logger.warning(
                "Degradación blanda de KMS: residuo normalizado=%.4e, β=%.4f.", 
                kms_residual, beta
            )
            return False, kms_residual, beta
        
        raise KMSConditionViolation(
            f"Violación catastrófica del equilibrio térmico KMS. Residuo normalizado={kms_residual:.4e} "
            f"> hard_tolerance={hard_tolerance:.4e}."
        )
    
    # ═══════════════════════════════════════════════════════════════════════
    # 2.3 MÉTODO FINAL DE FASE 2 — PUENTE A FASE 3
    # ═══════════════════════════════════════════════════════════════════════
    
    def execute_phase2_complete(
        self,
        rho_mac: ComplexMatrix,
        a_kms: ComplexMatrix,
        b_kms: ComplexMatrix,
        j_operator_empirical: Optional[ComplexMatrix] = None,
        beta_kms: float = 1.0,
    ) -> Phase2ModularOrientation:
        r"""
        Ejecuta la FASE 2 completa y retorna el artefacto terminal.
        Este método sirve como PUENTE a la FASE 3 — los valores calculados
        (type_classification, modular_flow_parameter) son consumidos por 
        Phase3_SovereignDecisionMaker para ajustar la cota de Lipschitz.
        
        MEJORA v4.0.0: Contrato explícito de fase con validación cruzada
        
        Returns:
            Phase2ModularOrientation: Certificado inmutable de la Fase 2
        """
        # Ejecutar verificación de conjugación modular
        (
            is_inv_ok, involution_resid, gns_resid, type_class
        ) = self._verify_modular_conjugation(
            rho_mac, a_kms, b_kms, j_operator_empirical
        )
        
        # Ejecutar verificación KMS
        is_kms_ok, kms_resid, flow_param = self._verify_kms_condition_numerical(
            rho_mac, a_kms, b_kms, beta=beta_kms
        )
        
        # Construir artefacto terminal — CONTINUIDAD A FASE 3
        return Phase2ModularOrientation(
            is_modular_involution_valid=is_inv_ok,
            modular_involution_residual=involution_resid,
            is_kms_equilibrium_valid=is_kms_ok,
            kms_residual=kms_resid,
            gns_norm_residual=gns_resid,
            modular_flow_parameter=flow_param,
            type_classification=type_class,
        )


