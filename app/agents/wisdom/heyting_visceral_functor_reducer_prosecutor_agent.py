        self.generation += 1
        gen = int(_report_attr(result.prosecution_report, "l3_generation", 0) or self.generation)
        homology_ok = result.betti_numbers[0] >= 1
        delta_beta = abs(result.betti_numbers[0] - 1) + abs(result.betti_numbers[1] - contract.betti_numbers[1])
        trace_ok = bool(contract.trace_preservation_ok) and abs(contract.trace_norm_measured - 1.0) < _TRACE_INVARIANT_TOL
        psd_ok = contract.psd_min_eigenvalue >= -1.0e-12
        heyting_ok = contract.heyting_algebra_closed and contract.reduced_verdict in (
            HeytingOmega3.COHERENT,
            HeytingOmega3.DEGRADED,
            HeytingOmega3.VETOED,
        )
        residuation_ok = bool(contract.residuation_sound)
        banach_ok = result.lipschitz_contraction <= _BANACH_LIPSCHITZ_BOUND + 1.0e-6
        symplectic_ok = not (result.symplectic_form_residual > 5.0e-2 and result.energy_drift > 0.35)
        dirac_consistent = True
        if contract.electron_anomaly_count > 0 and (not result.positron_auth_valid):
            dirac_consistent = result.prosecution_report.global_verdict == HeytingOmega3.VETOED
        qnd_ok = (result.back_action_db <= _QND_BACKACTION_TOL_DB) or (
            (not result.positron_auth_valid) and abs(result.back_action_db - _DIRAC_PUNITIVE_BACKACTION_DB) < 1.0e-6
        )
        bures_ok = bures <= 1.2 + 1.0e-9

        godel_valid = (
            homology_ok
            and delta_beta < 8
            and trace_ok
            and psd_ok
            and heyting_ok
            and residuation_ok
            and banach_ok
            and symplectic_ok
            and dirac_consistent
            and qnd_ok
            and bures_ok
        )
        h11 = max(1, int(result.betti_numbers[1]))
        h21 = max(0, int(result.betti_numbers[2]) + (0 if result.kam_tori_stable else 1))
