def _hermitian_sqrt(matrix: NDArray[np.complex128]) -> NDArray[np.complex128]:
    herm = 0.5 * (matrix + matrix.conj().T)
    eigvals, eigvecs = np.linalg.eigh(herm)
    sqrt_eigs = np.sqrt(np.clip(np.real(eigvals), 0.0, None))
    return (eigvecs * sqrt_eigs) @ eigvecs.conj().T


