def _shannon_entropy_histogram(samples: NDArray[np.float64], bins: int = 16) -> float:
    """Entropía de Shannon sobre masa de probabilidad (conteos/total). Nunca density=True."""
    if samples.size == 0:
        return 0.0
    if samples.ndim == 1:
        counts, _ = np.histogram(np.asarray(samples, dtype=np.float64), bins=int(bins))
    else:
        pts = np.asarray(samples, dtype=np.float64)
        if pts.shape[1] < 2:
            counts, _ = np.histogram(pts[:, 0], bins=int(bins))
        else:
            counts, _, _ = np.histogram2d(pts[:, 0], pts[:, 1], bins=int(bins))
    total = float(np.sum(counts))
    if total <= 0.0:
        return 0.0
    probs = counts.astype(np.float64) / total
    probs = probs[probs > 0.0]
    return float(-np.sum(probs * np.log2(probs)))


