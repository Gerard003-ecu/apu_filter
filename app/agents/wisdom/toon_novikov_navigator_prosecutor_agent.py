    # ─── D.1 — PRIMER MÉTODO DE LA FASE III: consumo del puente Φ₂₃' ────────
    def consume_phase2_agent_bridge(self, bridge: Phase2ToPhase3AgentBridge) -> bool:
        """Verifica la autenticidad criptográfica del puente Φ₂₃'."""
        payload = self._bridge23_payload(
            bridge.bundle, bridge.aggregate_rsi3_state, bridge.continuation_token
        )
        if not self._verify(_HMAC_DOMAIN_BRIDGE23_AGENT, payload, bridge.hmac_continuation):
            raise ValueError("Falla de autenticidad en puente Φ₂₃' del agente fiscal")
        if not self.continue_to_phase3_prosecutor_gate(bridge.bundle):
            raise ValueError("Bundle P2 inválido al consumir Φ₂₃'")
        return True

    # ─── D.2 — Verificación del certificado Banach RSI-3 (dual-dominio) ─────
    def verify_rsi3_banach_certificate(self, rsi3: NovikovProsecutorRSI3State) -> bool:
        """Revalida RSI-3: HMAC (motor v12 o agregado v13) ∧ ||T||<1 ∧ residuo<10⁻²."""
        payload = self._rsi3_cert_payload(rsi3)
        hmac_ok = any(
            self._verify(domain, payload, rsi3.banach_certificate_hmac)
            for domain in (_HMAC_DOMAIN_RSI3_CERT_ENGINE, _HMAC_DOMAIN_RSI3_AGG)
        )
        return bool(
            hmac_ok
            and rsi3.meta_operator_norm < 1.0
            and rsi3.fixed_point_residual < _RSI3_RESIDUAL_BOUND
            and rsi3.banach_convergence_certified
        )

