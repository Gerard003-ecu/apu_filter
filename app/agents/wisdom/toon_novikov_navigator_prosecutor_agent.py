        left = self.monadic_compose_sovereign_passports(p, eta)
        right = self.monadic_compose_sovereign_passports(eta, p)

        def _alg(a: NovikovProsecutorSovereignPassport) -> Tuple[Any, ...]:
            return (
                int(a.global_heyting_verdict.value),
                bool(a.crowbar_triggered),
                round(a.crowbar_latency_ns, 6),
                round(a.released_energy_kev, 8),
                round(a.banach_lipschitz_contraction, 8),
                bool(a.rsi3_banach_certified),
                bool(a.homoclinic_tangency_present),
                bool(a.monodromy_is_symplectic),
            )

        m1 = _alg(left) == _alg(p)
        m2 = _alg(right) == _alg(p)
        m3 = True
        if q is not None and r is not None:
            assoc_l = self.monadic_compose_sovereign_passports(
                self.monadic_compose_sovereign_passports(p, q), r
            )
            assoc_r = self.monadic_compose_sovereign_passports(
                p, self.monadic_compose_sovereign_passports(q, r)
            )
            m3 = _alg(assoc_l) == _alg(assoc_r)
        return {"M1_mu_Teta": m1, "M2_mu_etaT": m2, "M3_assoc": m3}

