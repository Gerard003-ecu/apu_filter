def _now_utc_iso() -> str:
    """Instante UTC canónico para trazabilidad."""
    return datetime.now(timezone.utc).isoformat()


def _unique_reasons(reasons: Iterable[str]) -> Tuple[str, ...]:
    """Deduplica razones preservando el orden de primera aparición."""
    seen = set()
    ordered: List[str] = []
    for reason in reasons:
        text = str(reason).strip()
        if not text or text in seen:
            continue
        seen.add(text)
        ordered.append(text)
    return tuple(ordered)


def _stable_sha256(payload: Mapping[str, Any]) -> str:
    """Huella canónica SHA-256 de un mapeo JSON-serializable."""
    blob = json.dumps(
        payload,
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=True,
        default=str,
    )
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()


def _heyting_meet(left: float, right: float) -> float:
    r"""Ínfimo de Gödel en \(\Omega_3\): \(a \wedge b = \min(a, b)\)."""
    return float(min(left, right))


def _heyting_implies(antecedent: float, consequent: float) -> float:
    r"""
    Implicación intuicionista de Gödel:

    \[
        a \to b
        =
        \begin{cases}
            1 & \text{si } a \le b, \\
            b & \text{en otro caso.}
        \end{cases}
    \]
    """
    if antecedent <= consequent + 8.0 * _MACHINE_EPS:
        return _OMEGA3_TRUE
    return float(consequent)


def _geometric_mean(values: Sequence[float]) -> float:
    """Media geométrica de márgenes en (0, 1], con piso numérico."""
    if not values:
        return 1.0
    acc = 0.0
    for item in values:
        if not math.isfinite(item) or item <= 0.0:
            return 0.0
        acc += math.log(max(item, _MACHINE_EPS))
    return float(math.exp(acc / float(len(values))))


def _safe_ratio(numerator: float, denominator: float) -> float:
    r"""Cociente protegido en la compactificación \(\mathbb{R} \cup \{\infty\}\)."""
    num = float(numerator)
    den = float(denominator)
    if not math.isfinite(num):
        return math.inf
    if not math.isfinite(den) or den == 0.0:
        return 1.0 if num == 0.0 else math.inf
    ratio = num / den
    return float(ratio) if math.isfinite(ratio) else math.inf


def _chsh_canonical(e11: float, e12: float, e21: float, e22: float) -> float:
    r"""Patrón canónico \(|E_{11}+E_{12}+E_{21}-E_{22}|\)."""
    return float(abs(e11 + e12 + e21 - e22))


def _chsh_max_sign_patterns(e11: float, e12: float, e21: float, e22: float) -> float:
    r"""
    Máximo CHSH sobre los cuatro patrones con un único minus:

    \[
        |E_{11}+E_{12}+E_{21}-E_{22}|,\;
        |E_{11}+E_{12}-E_{21}+E_{22}|,\;
        |E_{11}-E_{12}+E_{21}+E_{22}|,\;
        |-E_{11}+E_{12}+E_{21}+E_{22}|.
    \]
    """
    patterns = (
        abs(e11 + e12 + e21 - e22),
        abs(e11 + e12 - e21 + e22),
        abs(e11 - e12 + e21 + e22),
        abs(-e11 + e12 + e21 + e22),
    )
    return float(max(patterns))


def _copy_array(obj: Any) -> Any:
    """Copia C-contigua defensiva; si falla, devuelve el objeto original."""
    try:
        return np.array(obj, copy=True, order="C")
    except Exception:
        return obj


def _matrix_digest(obj: Any, kind: str) -> str:
    """Huella SHA-256 del contenido numérico de un operador (o vacío)."""
    if obj is None:
        return hashlib.sha256(b"none").hexdigest()
    try:
        arr = np.asarray(obj)
        shape = str(tuple(int(x) for x in arr.shape)).encode("utf-8")
        if kind == "int":
            if arr.dtype == object or np.issubdtype(arr.dtype, np.integer):
                text = ";".join(
                    ",".join(str(int(x)) for x in np.atleast_1d(row).tolist())
                    for row in np.atleast_2d(arr)
                )
                return hashlib.sha256(shape + b"|int|" + text.encode("utf-8")).hexdigest()
            work = np.asarray(np.real(arr), dtype=np.float64)
            if not np.all(np.isfinite(work)):
                return hashlib.sha256(shape + b"|nonfinite").hexdigest()
            rounded = np.ascontiguousarray(np.rint(work).astype(np.int64))
            return hashlib.sha256(shape + b"|rint|" + rounded.tobytes()).hexdigest()
        if kind == "complex":
            data = np.ascontiguousarray(np.asarray(arr, dtype=np.complex128))
            if not np.all(np.isfinite(data)):
                return hashlib.sha256(shape + b"|nonfinite").hexdigest()
            return hashlib.sha256(shape + b"|c128|" + data.tobytes()).hexdigest()
        data = np.ascontiguousarray(np.asarray(arr, dtype=np.float64))
        if not np.all(np.isfinite(data)):
            return hashlib.sha256(shape + b"|nonfinite").hexdigest()
        return hashlib.sha256(shape + b"|f64|" + data.tobytes()).hexdigest()
    except Exception:
        return hashlib.sha256(repr(obj).encode("utf-8", errors="replace")).hexdigest()


