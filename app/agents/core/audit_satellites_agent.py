    def _instantiate_engine(self) -> AuditSatellites:
        """
        Instancia el motor `AuditSatellites`.

        Intenta usar parámetros avanzados del motor evolucionado. Si el motor
        es la versión original, cae elegantemente a la API básica.
        """
        base_kwargs: Dict[str, Any] = {
            "dimension_n": self._n,
            "safety_margin": self._safety_margin,
        }
        advanced_kwargs: Dict[str, Any] = {
            "rng_seed": self._rng_seed,
            "choi_cp_veto_tolerance": abs(self._choi_cp_veto_thresh),
            "choi_tp_veto_tolerance": self._choi_tp_veto_thresh,
            "choi_hermitian_veto_tolerance": self._choi_herm_veto_thresh,
        }
        try:
            return AuditSatellites(**base_kwargs, **advanced_kwargs)
        except TypeError:
            try:
                return AuditSatellites(**base_kwargs)
            except TypeError:
                return AuditSatellites(self._n, self._safety_margin)

    @staticmethod
    def _normalize_verdict(verdict: Any) -> str:
        """Normaliza veredictos a \(\Omega_3\)."""
        v = str(verdict).strip().upper()
        if v in _VERDICT_ORDER:
            return v
        if v in {"TRUE", "OK", "COHERENCE", "STABLE", "PASS"}:
            return _VERDICT_COHERENT
        if v in {"WARN", "WARNING", "UNSTABLE", "DEGRADED"}:
            return _VERDICT_DEGRADED
        return _VERDICT_VETOED

    @staticmethod
    def _safe_float(
        value: Any,
        default: float,
        allow_inf: bool = False,
    ) -> float:
        """Extrae float de forma defensiva."""
        try:
            x = float(value)
        except Exception:
            return float(default)
        if math.isfinite(x):
            return x
        if allow_inf and math.isinf(x):
            return x
        return float(default)

    @staticmethod
    def _safe_optional_bool(value: Any) -> Optional[bool]:
        """Extrae bool opcional de forma defensiva."""
        if value is None:
            return None
        try:
            return bool(value)
        except Exception:
            return None

    @staticmethod
    def _safe_int(value: Any, default: int = 0) -> int:
        """Extrae entero de forma defensiva."""
        try:
            return int(value)
        except Exception:
            return int(default)

    @staticmethod
    def _safe_str(value: Any, default: str = "") -> str:
        """Extrae texto de forma defensiva."""
        if value is None:
            return default
        try:
            return str(value)
        except Exception:
            return default

    def _join_verdicts(self, verdict_a: str, verdict_b: str) -> str:
        r"""
        Join de severidad en \(\Omega_3\) ≡ meet de Gödel sobre valores de
        verdad: \(\mathrm{tv}(a \sqcup b) = \mathrm{tv}(a) \wedge \mathrm{tv}(b)\).
        """
        a = _VERDICT_ORDER[self._normalize_verdict(verdict_a)]
        b = _VERDICT_ORDER[self._normalize_verdict(verdict_b)]
        return _ORDER_TO_VERDICT[max(a, b)]

    def verify_causal_coherence(
        self,
        min_eig: float,
        tp_diff: float,
    ) -> bool:
        r"""
        [COMPATIBILIDAD - FASE ORIENT]

        Verifica que el canal de frontera sea CPTP bajo los umbrales del agente:
        \[
            \lambda_{\min}(C_{\mathcal{E}}) \ge \tau_{\mathrm{CP}}
            \quad \land \quad
            \|\operatorname{Tr}_2(C_{\mathcal{E}}) - I\| \le \tau_{\mathrm{TP}}.
        \]
        """
        try:
            min_eig_f = float(min_eig)
            tp_f = float(tp_diff)
        except Exception:
            return False
        if not math.isfinite(min_eig_f) or not math.isfinite(tp_f):
            return False
        return bool(min_eig_f >= self._choi_cp_thresh and tp_f <= self._choi_tp_thresh)

    def verify_homology_coherence(
        self,
        torsion_coeffs: List[int],
    ) -> bool:
        r"""
        [COMPATIBILIDAD - FASE ORIENT]

        Verifica que el subgrupo de torsión homológica sea nulo:
        \[
            \operatorname{Tor}(H_k(\partial K;\mathbb{Z})) = 0.
        \]
        """
        try:
            return len(list(torsion_coeffs)) == 0
        except Exception:
            return False

    def evaluate_heyting_decision_lattice(
        self,
        is_homology_coherent: bool,
        is_causal_coherent: bool,
        chsh_val: float,
        torsion_coeffs: List[int],
        min_eig: float,
        tp_diff: float,
    ) -> str:
        r"""
        [COMPATIBILIDAD - FASE DECIDE]

        Clasificación trivalente ordinal de Heyting:
        \[
            \Omega_3 = \{\mathtt{COHERENT}, \mathtt{DEGRADED}, \mathtt{VETOED}\}.
        \]
        """
        try:
            chsh_f = float(chsh_val)
        except Exception:
            chsh_f = math.inf
        try:
            min_eig_f = float(min_eig)
        except Exception:
            min_eig_f = -math.inf
        try:
            tp_f = float(tp_diff)
        except Exception:
            tp_f = math.inf

        bell_tol = max(1.0e-12, 100.0 * _MACHINE_EPS)
        if (
            not is_homology_coherent
            or not math.isfinite(min_eig_f)
            or not math.isfinite(tp_f)
            or not math.isfinite(chsh_f)
            or min_eig_f < self._choi_cp_veto_thresh
            or tp_f > self._choi_tp_veto_thresh
            or chsh_f > _TSIRELSON_LIMIT + bell_tol
        ):
            return _VERDICT_VETOED

        if (
            len(list(torsion_coeffs)) > 0
            or not is_causal_coherent
            or min_eig_f < self._choi_cp_thresh
            or tp_f > self._choi_tp_thresh
            or chsh_f > self._bell_thresh + bell_tol
        ):
            return _VERDICT_DEGRADED

        return _VERDICT_COHERENT

