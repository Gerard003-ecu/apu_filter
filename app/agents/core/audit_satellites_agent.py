# FASE 3 — ACTUACIÓN, CERTIFICADO Y ORQUESTACIÓN OODA
# ════════════════════════════════════════════════════════════════════════════


class Phase3ActuationCertificateKernel(Phase2OrientEngineAuditKernel):
    r"""
    FASE 3: Actuación y certificación.

    El primer método, `act_on_agent_pre_decision`, consume el
    `AgentPreDecision` producido por `prepare_agent_pre_decision` (Fase 2).

    Responsabilidades:
      1. Activar o inhibir el interlock ciber-físico (fail-closed).
      2. Emitir `AuditSatelliteCertificate` con doble huella SHA-256:
         isomorfa (sin reloj) y de no-repudio (con reloj).
      3. Exponer ciclo OODA síncrono y asíncrono, con semáforo de lote.
      4. Permitir verificación independiente del certificado emitido.
    """

    def __init__(
        self,
        dimension_n: int,
        safety_margin: float = 1.0,
        choi_cp_threshold: float = -1.0e-12,
        choi_tp_threshold: float = 1.0e-10,
        bell_threshold: float = 2.0,
        *,
        crowbar_base_latency_ns: float = _CROWBAR_IRAM_LATENCY_NS,
        crowbar_jitter_ns: float = 3.8,
        crowbar_min_latency_ns: float = 380.0,
        crowbar_max_latency_ns: float = 420.0,
        gpio_pin: str = "GPIO14",
        async_timeout_s: float = 5.0,
        max_batch: int = _DEFAULT_MAX_BATCH,
        **kwargs: Any,
    ) -> None:
        super().__init__(
            dimension_n,
            safety_margin,
            choi_cp_threshold,
            choi_tp_threshold,
            bell_threshold,
            **kwargs,
        )

        self._crowbar_base_latency_ns = self._finite_float(
            crowbar_base_latency_ns,
            "crowbar_base_latency_ns",
            0.0,
        )
        self._crowbar_jitter_ns = self._finite_float(
            crowbar_jitter_ns,
            "crowbar_jitter_ns",
            0.0,
        )
        self._crowbar_min_latency_ns = self._finite_float(
            crowbar_min_latency_ns,
            "crowbar_min_latency_ns",
            0.0,
        )
        self._crowbar_max_latency_ns = self._finite_float(
            crowbar_max_latency_ns,
            "crowbar_max_latency_ns",
            self._crowbar_min_latency_ns,
        )
        if self._crowbar_max_latency_ns < self._crowbar_min_latency_ns:
            self._crowbar_max_latency_ns = self._crowbar_min_latency_ns

        self._gpio_pin = str(gpio_pin)
        self._async_timeout_s = self._finite_float(
            async_timeout_s,
            "async_timeout_s",
            0.0,
        )
        max_batch_n = int(max_batch)
        if max_batch_n <= 0:
            raise ValueError("max_batch debe ser entero positivo.")
        self._max_batch = max_batch_n

    def _fire_crowbar(self, reason: str) -> AuditActuationReport:
        """Dispara el crowbar simulado con jitter gaussiano acotado."""
        if self._crowbar_jitter_ns > 0.0:
            jitter = float(self._rng.normal(0.0, self._crowbar_jitter_ns))
        else:
            jitter = 0.0
        latency = self._crowbar_base_latency_ns + jitter
        latency = float(
            np.clip(
                latency,
                self._crowbar_min_latency_ns,
                self._crowbar_max_latency_ns,
            )
        )
        logger.critical(
            "¡VETO SÍNCRONO DE FRONTERA DETECTADO POR EL SOBERANO DE AUDITORÍA! "
            "Bypass Crowbar BT151 [%s] gatillado en IRAM. Latencia: %.2f ns. "
            "Razón: %s",
            self._gpio_pin,
            latency,
            reason,
        )
        return AuditActuationReport(
            interlock_fired=True,
            actuation_latency_ns=latency,
            gpio_pin=self._gpio_pin,
            timestamp_utc=self._now_utc_iso(),
            reason=reason,
        )

    def _no_actuation(self, reason: str) -> AuditActuationReport:
        """Inhibe el interlock físico."""
        return AuditActuationReport(
            interlock_fired=False,
            actuation_latency_ns=0.0,
            gpio_pin=self._gpio_pin,
            timestamp_utc=self._now_utc_iso(),
            reason=reason,
        )

    def act_on_agent_pre_decision(
        self, decision: AgentPreDecision
    ) -> AuditActuationReport:
        r"""
        PRIMER MÉTODO DE LA FASE 3.

        Continuación formal de `prepare_agent_pre_decision` (Fase 2).

        Consume `AgentPreDecision` y decide la actuación ciber-física del
        crowbar perimetral. Política fail-closed: sólo VETOED dispara.
        """
        if decision.final_verdict == _VERDICT_VETOED:
            reason = ";".join(decision.reasons)[:200]
            return self._fire_crowbar(reason)
        return self._no_actuation("boundary_not_vetoed")

    def act_hardware_interlock_simulation(
        self,
        verdict: str,
        telemetry_hash: str,
    ) -> Tuple[bool, float]:
        r"""
        [COMPATIBILIDAD - FASE ACT]

        Simula la actuación del disyuntor de potencia.

        Si Heyting colapsa a VETOED, la ISR cargada en IRAM conmuta GPIO14:
        \[
            t_{\mathrm{actuation}} \le \tau_{\mathrm{IRAM}} = 400\text{ ns}.
        \]
        """
        normalized = self._normalize_verdict(verdict)
        if normalized == _VERDICT_VETOED:
            safe_hash = str(telemetry_hash)[:16]
            report = self._fire_crowbar(f"legacy_api_veto:{safe_hash}")
            return report.interlock_fired, report.actuation_latency_ns
        return False, 0.0

    def _decision_fingerprint(
        self,
        decision: AgentPreDecision,
        actuation: AuditActuationReport,
    ) -> str:
        """Huella isomorfa (sin reloj) del par (decisión, actuación lógica)."""
        return _stable_sha256(
            {
                "dimension_n": self._n,
                "final_verdict": decision.final_verdict,
                "engine_verdict": decision.engine_verdict,
                "agent_verdict": decision.agent_verdict,
                "truth_value": decision.truth_value,
                "torsion": list(decision.torsion_coefficients),
                "invariant_factors": list(decision.invariant_factors),
                "min_eigenvalue": decision.min_eigenvalue,
                "tp_residual": decision.tp_residual,
                "chsh_value": decision.chsh_value,
                "agent_chsh_value": decision.agent_chsh_value,
                "is_homology_coherent": decision.is_homology_coherent,
                "is_causal_coherent": decision.is_causal_coherent,
                "is_bell_coherent": decision.is_bell_coherent,
                "is_bell_classical": decision.is_bell_classical,
                "correlations_physical": decision.correlations_physical,
                "inputs_sha256": decision.inputs_sha256,
                "engine_certificate_sha256": decision.engine_certificate_sha256,
                "interlock_fired": bool(actuation.interlock_fired),
                "gpio_pin": self._gpio_pin,
                "reasons": list(decision.reasons),
            }
        )

    def synthesize_audit_certificate(
        self,
        decision: AgentPreDecision,
        actuation: AuditActuationReport,
    ) -> AuditSatelliteCertificate:
        """Emite el certificado orbital firmado (isomorfo + no-repudio)."""
        timestamp_utc = self._now_utc_iso()
        decision_sha = self._decision_fingerprint(decision, actuation)
        signature = _stable_sha256(
            {
                "decision_sha256": decision_sha,
                "timestamp_utc": timestamp_utc,
                "observation_timestamp_utc": decision.observation_timestamp_utc,
                "actuation_latency_ns": float(actuation.actuation_latency_ns),
                "actuation_timestamp_utc": actuation.timestamp_utc,
                "phase": _AGENT_PHASE,
                "version": __version__,
            }
        )

        if decision.final_verdict == _VERDICT_DEGRADED:
            logger.warning(
                "Aduana degradada. Homología=%s | Causal=%s | CHSH=%.6f | Razones=%s",
                decision.is_homology_coherent,
                decision.is_causal_coherent,
                decision.chsh_value,
                ";".join(decision.reasons),
            )
        elif decision.final_verdict == _VERDICT_COHERENT:
            logger.info(
                "Aduana coherente. λ_min(C)=%.6e | TP=%.3e | CHSH=%.6f",
                decision.min_eigenvalue,
                decision.tp_residual,
                decision.chsh_value,
            )

        return AuditSatelliteCertificate(
            phase=_AGENT_PHASE,
            heyting_verdict=decision.final_verdict,
            smith_torsion_coefficients=tuple(decision.torsion_coefficients),
            choi_minimum_eigenvalue=float(decision.min_eigenvalue),
            choi_trace_preserving_residual=float(decision.tp_residual),
            bell_chsh_parameter=float(decision.chsh_value),
            is_causal_coherent=bool(decision.is_causal_coherent),
            is_cohomology_coherent=bool(decision.is_homology_coherent),
            hardware_interlock_fired=bool(actuation.interlock_fired),
            actuation_latency_ns=float(actuation.actuation_latency_ns),
            telemetry_payload_hash=decision.inputs_sha256,
            engine_verdict=decision.engine_verdict,
            agent_verdict=decision.agent_verdict,
            choi_is_cptp=bool(decision.engine_is_cptp or False),
            choi_is_cp=bool(decision.engine_is_cp or False),
            choi_is_tp=bool(decision.engine_is_tp or False),
            choi_is_hermitian=bool(decision.engine_is_hermitian or False),
            choi_trace_residual=float(decision.choi_trace_residual),
            choi_hermitian_residual=float(decision.choi_hermitian_residual),
            bell_is_classical=bool(decision.is_bell_classical),
            bell_tsirelson_bound=_TSIRELSON_LIMIT,
            heyting_truth_value=float(decision.truth_value),
            timestamp_utc=timestamp_utc,
            reasons=decision.reasons,
            decision_sha256=decision_sha,
            digital_signature_sha256=signature,
            snf_complete=decision.snf_complete,
            invariant_factors=tuple(decision.invariant_factors),
            choi_kraus_rank=int(decision.choi_kraus_rank),
            correlations_physical=bool(decision.correlations_physical),
            gpio_pin=self._gpio_pin,
            dimension_n=self._n,
            engine_certificate_sha256=decision.engine_certificate_sha256,
            truth_continuous=float(decision.truth_continuous),
        )

    def verify_audit_certificate(
        self, certificate: AuditSatelliteCertificate
    ) -> bool:
        """Verifica la huella isomorfa reconstruible de un certificado."""
        try:
            expected = _stable_sha256(
                {
                    "dimension_n": certificate.dimension_n or self._n,
                    "final_verdict": certificate.heyting_verdict,
                    "engine_verdict": certificate.engine_verdict,
                    "agent_verdict": certificate.agent_verdict,
                    "truth_value": certificate.heyting_truth_value,
                    "torsion": list(certificate.smith_torsion_coefficients),
                    "invariant_factors": list(certificate.invariant_factors),
                    "min_eigenvalue": certificate.choi_minimum_eigenvalue,
                    "tp_residual": certificate.choi_trace_preserving_residual,
                    "chsh_value": certificate.bell_chsh_parameter,
                    "agent_chsh_value": certificate.bell_chsh_parameter,
                    "is_homology_coherent": certificate.is_cohomology_coherent,
                    "is_causal_coherent": certificate.is_causal_coherent,
                    "is_bell_coherent": (
                        math.isfinite(certificate.bell_chsh_parameter)
                        and certificate.bell_chsh_parameter
                        <= certificate.bell_tsirelson_bound
                        + max(1.0e-12, 100.0 * _MACHINE_EPS)
                        and certificate.correlations_physical
                    ),
                    "is_bell_classical": certificate.bell_is_classical,
                    "correlations_physical": certificate.correlations_physical,
                    "inputs_sha256": certificate.telemetry_payload_hash,
                    "engine_certificate_sha256": certificate.engine_certificate_sha256,
                    "interlock_fired": bool(certificate.hardware_interlock_fired),
                    "gpio_pin": certificate.gpio_pin or self._gpio_pin,
                    "reasons": list(certificate.reasons),
                }
            )
            if certificate.decision_sha256 == expected:
                return True
            # Recalcular sin el CHSH agente (el certificado público no lo
            # duplica: se usa el parámetro Bell del motor).
            expected_pub = _stable_sha256(
                {
                    "dimension_n": certificate.dimension_n or self._n,
                    "final_verdict": certificate.heyting_verdict,
                    "engine_verdict": certificate.engine_verdict,
                    "agent_verdict": certificate.agent_verdict,
                    "truth_value": certificate.heyting_truth_value,
                    "torsion": list(certificate.smith_torsion_coefficients),
                    "invariant_factors": list(certificate.invariant_factors),
                    "min_eigenvalue": certificate.choi_minimum_eigenvalue,
                    "tp_residual": certificate.choi_trace_preserving_residual,
                    "chsh_value": certificate.bell_chsh_parameter,
                    "agent_chsh_value": certificate.bell_chsh_parameter,
                    "is_homology_coherent": certificate.is_cohomology_coherent,
                    "is_causal_coherent": certificate.is_causal_coherent,
                    "is_bell_coherent": certificate.correlations_physical
                    and math.isfinite(certificate.bell_chsh_parameter)
                    and certificate.bell_chsh_parameter
                    <= _TSIRELSON_LIMIT + max(1.0e-12, 100.0 * _MACHINE_EPS),
                    "is_bell_classical": certificate.bell_is_classical,
                    "correlations_physical": certificate.correlations_physical,
                    "inputs_sha256": certificate.telemetry_payload_hash,
                    "engine_certificate_sha256": certificate.engine_certificate_sha256,
                    "interlock_fired": bool(certificate.hardware_interlock_fired),
                    "gpio_pin": certificate.gpio_pin or self._gpio_pin,
                    "reasons": list(certificate.reasons),
                }
            )
            return certificate.decision_sha256 == expected_pub
        except Exception:
            return False

    def execute_full_audit_cycle(
        self,
        boundary_matrix: np.ndarray,
        Choi_matrix: np.ndarray,
        bell_correlations: Tuple[float, float, float, float],
    ) -> AuditSatelliteCertificate:
        r"""
        API síncrona principal compatible con la versión original.

        Orquesta el ciclo OODA completo de las tres fases anidadas:
        \[
            \mathrm{Observe}
            \xrightarrow{\texttt{observe\_audit\_event}}
            \mathrm{Orient}
            \xrightarrow{\texttt{orient\_audit\_observation}}
            \mathrm{Decide}
            \xrightarrow{\texttt{prepare\_agent\_pre\_decision}}
            \mathrm{Act}
            \xrightarrow{\texttt{act\_on\_agent\_pre\_decision}}
            \mathrm{Certify}.
        \]
        """
        logger.debug("Fase Observe: capturando evidencia de auditoría homológica.")
        observation = self.observe_audit_event(
            boundary_matrix=boundary_matrix,
            Choi_matrix=Choi_matrix,
            bell_correlations=bell_correlations,
        )

        logger.debug("Fase Orient: fiscalizando motor de auditoría de frontera.")
        evidence = self.orient_audit_observation(observation)

        logger.debug("Fase Decide: resolviendo retículo de Heyting Ω₃.")
        decision = self.prepare_agent_pre_decision(evidence)

        logger.debug("Fase Act: evaluando interlock ciber-físico perimetral.")
        actuation = self.act_on_agent_pre_decision(decision)
        certificate = self.synthesize_audit_certificate(decision, actuation)

        if decision.final_verdict == _VERDICT_VETOED:
            logger.error(
                "Fase Decide/Act: VETO DE AUDITORÍA DETECTADO. "
                "Torsión: %s, Min Choi Autovalor: %.6f, Residuo TP: %.6e, Bell-CHSH: %.4f",
                list(decision.torsion_coefficients),
                decision.min_eigenvalue,
                decision.tp_residual,
                decision.chsh_value,
            )
        return certificate

    async def _call_engine_async(
        self,
        observation: AuditObservation,
    ) -> Dict[str, Any]:
        """Invoca asíncronamente al motor si expone API async."""
        if not hasattr(self._engine, "execute_audit_cycle_async"):
            return await asyncio.to_thread(
                self._engine.execute_audit_cycle,
                observation.boundary_matrix,
                observation.Choi_matrix,
                observation.bell_correlations,
            )
        kwargs: Dict[str, Any] = {
            "boundary_matrix": observation.boundary_matrix,
            "Choi_matrix": observation.Choi_matrix,
            "bell_correlations": observation.bell_correlations,
        }
        try:
            return await self._engine.execute_audit_cycle_async(
                timeout_s=self._async_timeout_s,
                **kwargs,
            )
        except TypeError:
            return await asyncio.to_thread(
                self._engine.execute_audit_cycle,
                observation.boundary_matrix,
                observation.Choi_matrix,
                observation.bell_correlations,
            )

    async def orient_audit_observation_async(
        self,
        observation: AuditObservation,
    ) -> EngineAuditEvidence:
        """Versión asíncrona de la auditoría de Fase 2."""
        try:
            result = await self._call_engine_async(observation)
            if not isinstance(result, dict):
                raise TypeError("El motor de auditoría no devolvió un diccionario.")
            return self._extract_engine_evidence(result, observation)
        except Exception as exc:  # pragma: no cover - defensa ciber-física
            return self._fail_safe_evidence(observation, exc)

    def _normalize_async_request(
        self,
        request: Mapping[str, Any],
    ) -> Dict[str, Any]:
        """Extrae y valida las claves admitidas de una petición OODA asíncrona."""
        allowed = {
            "boundary_matrix",
            "Choi_matrix",
            "bell_correlations",
        }
        unknown = set(request.keys()) - allowed
        if unknown:
            raise ValueError(
                f"Claves no admitidas en request asíncrono: {sorted(unknown)}"
            )
        if "boundary_matrix" not in request or "Choi_matrix" not in request:
            raise ValueError("Cada request requiere 'boundary_matrix' y 'Choi_matrix'.")
        if "bell_correlations" not in request:
            raise ValueError("Cada request requiere 'bell_correlations'.")
        return {
            "boundary_matrix": request["boundary_matrix"],
            "Choi_matrix": request["Choi_matrix"],
            "bell_correlations": request["bell_correlations"],
        }

    async def execute_full_audit_cycle_async(
        self,
        boundary_matrix: np.ndarray,
        Choi_matrix: np.ndarray,
        bell_correlations: Tuple[float, float, float, float],
        timeout_s: Optional[float] = None,
    ) -> AuditSatelliteCertificate:
        r"""
        API asíncrona principal del agente soberano.

        Ejecuta el ciclo OODA completo sin bloquear el lazo de eventos.
        El timeout cubre la orientación (motor); Observe/Decide/Act son
        locales y acotados.
        """
        observation = self.observe_audit_event(
            boundary_matrix=boundary_matrix,
            Choi_matrix=Choi_matrix,
            bell_correlations=bell_correlations,
        )
        timeout = self._async_timeout_s if timeout_s is None else float(timeout_s)
        if timeout > 0.0:
            evidence = await asyncio.wait_for(
                self.orient_audit_observation_async(observation),
                timeout=timeout,
            )
        else:
            evidence = await self.orient_audit_observation_async(observation)

        decision = self.prepare_agent_pre_decision(evidence)
        actuation = self.act_on_agent_pre_decision(decision)
        return self.synthesize_audit_certificate(decision, actuation)

    async def execute_full_audit_cycle_batch_async(
        self,
        requests: Iterable[Mapping[str, Any]],
        *,
        max_concurrency: int = 8,
        return_exceptions: bool = False,
    ) -> List[Any]:
        """Ejecuta múltiples ciclos OODA asíncronos con semáforo de concurrencia."""
        materialized = list(requests)
        if len(materialized) > self._max_batch:
            raise ValueError(
                f"El lote ({len(materialized)}) excede max_batch={self._max_batch}."
            )
        concurrency = max(int(max_concurrency), 1)
        semaphore = asyncio.Semaphore(concurrency)

        async def _run(request: Mapping[str, Any]) -> AuditSatelliteCertificate:
            params = self._normalize_async_request(request)
            async with semaphore:
                return await self.execute_full_audit_cycle_async(**params)

        tasks = [_run(request) for request in materialized]
        return list(await asyncio.gather(*tasks, return_exceptions=return_exceptions))


