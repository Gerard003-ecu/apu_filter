    def _extract_engine_evidence(
        self,
        result: Dict[str, Any],
        observation: AuditObservation,
    ) -> EngineAuditEvidence:
        """Extrae y normaliza la evidencia emitida por el motor."""
        engine_verdict = self._normalize_verdict(
            result.get("heyting_verdict", _VERDICT_VETOED)
        )

        torsion_raw = result.get("smith_torsion_coefficients", [])
        torsion: List[int] = []
        if isinstance(torsion_raw, (list, tuple)):
            for x in torsion_raw:
                try:
                    torsion.append(int(x))
                except Exception:
                    torsion.append(0)

        inv_raw = result.get("invariant_factors", torsion)
        invariants: List[int] = []
        if isinstance(inv_raw, (list, tuple)):
            for x in inv_raw:
                try:
                    invariants.append(int(x))
                except Exception:
                    continue

        min_eig = self._safe_float(
            result.get("choi_minimum_eigenvalue"),
            -math.inf,
            allow_inf=True,
        )
        tp_residual = self._safe_float(
            result.get("choi_trace_preserving_residual"),
            math.inf,
            allow_inf=True,
        )
        chsh_value = self._safe_float(
            result.get("bell_chsh_parameter"),
            math.inf,
            allow_inf=True,
        )

        engine_is_homology_coherent = self._safe_optional_bool(
            result.get("is_homology_coherent")
        )
        if "is_causal_coherent" in result:
            engine_is_causal_coherent = self._safe_optional_bool(
                result.get("is_causal_coherent")
            )
        elif "choi_is_cptp" in result:
            engine_is_causal_coherent = self._safe_optional_bool(
                result.get("choi_is_cptp")
            )
        else:
            engine_is_causal_coherent = None

        engine_is_cptp = self._safe_optional_bool(result.get("choi_is_cptp"))
        engine_is_cp = self._safe_optional_bool(result.get("choi_is_cp"))
        engine_is_tp = self._safe_optional_bool(result.get("choi_is_tp"))
        engine_is_hermitian = self._safe_optional_bool(result.get("choi_is_hermitian"))
        choi_is_unital = self._safe_optional_bool(result.get("choi_is_unital"))

        choi_trace_residual = self._safe_float(
            result.get("choi_trace_residual"),
            math.inf,
            allow_inf=True,
        )
        choi_hermitian_residual = self._safe_float(
            result.get("choi_hermitian_residual"),
            math.inf,
            allow_inf=True,
        )
        choi_unital_residual = self._safe_float(
            result.get("choi_unital_residual"),
            math.inf,
            allow_inf=True,
        )
        engine_bell_is_classical = self._safe_optional_bool(
            result.get("bell_is_classical")
        )
        engine_bell_physical = self._safe_optional_bool(
            result.get("bell_correlations_physical")
        )
        engine_interlock = self._safe_optional_bool(
            result.get("hardware_interlock_fired")
        )
        snf_complete = self._safe_optional_bool(result.get("snf_complete"))

        engine_reasons_raw = result.get("reasons", [])
        if isinstance(engine_reasons_raw, (list, tuple)):
            engine_reasons = tuple(str(x) for x in engine_reasons_raw if str(x))
        elif engine_reasons_raw:
            engine_reasons = (str(engine_reasons_raw),)
        else:
            engine_reasons = ()

        agent_chsh = observation.agent_chsh_value
        if math.isfinite(chsh_value) and math.isfinite(agent_chsh):
            chsh_delta = abs(float(chsh_value) - float(agent_chsh))
        else:
            chsh_delta = math.inf

        expected_interlock = engine_verdict == _VERDICT_VETOED
        if engine_interlock is None:
            interlock_ok = True
        else:
            interlock_ok = bool(engine_interlock) is expected_interlock

        if snf_complete is None:
            snf_ok = True
        elif engine_is_homology_coherent is False and snf_complete is False:
            snf_ok = True
        elif engine_is_homology_coherent is True and snf_complete is False:
            snf_ok = False
        else:
            snf_ok = True

        dim_engine = result.get("dimension_n")
        extra_reasons: List[str] = list(observation.notes)
        if dim_engine is not None and self._safe_int(dim_engine, self._n) != self._n:
            extra_reasons.append("engine_dimension_mismatch")
            snf_ok = False

        return EngineAuditEvidence(
            is_valid=True,
            engine_verdict=engine_verdict,
            torsion_coefficients=tuple(torsion),
            min_eigenvalue=min_eig,
            tp_residual=tp_residual,
            chsh_value=chsh_value,
            engine_is_homology_coherent=engine_is_homology_coherent,
            engine_is_causal_coherent=engine_is_causal_coherent,
            engine_is_cptp=engine_is_cptp,
            engine_is_cp=engine_is_cp,
            engine_is_tp=engine_is_tp,
            engine_is_hermitian=engine_is_hermitian,
            choi_trace_residual=choi_trace_residual,
            choi_hermitian_residual=choi_hermitian_residual,
            engine_bell_is_classical=engine_bell_is_classical,
            engine_reasons=_unique_reasons(list(engine_reasons) + extra_reasons),
            inputs_sha256=observation.inputs_sha256,
            observation_timestamp_utc=observation.timestamp_utc,
            timestamp_utc=self._now_utc_iso(),
            snf_complete=snf_complete,
            smith_matrix_rank=self._safe_int(result.get("smith_matrix_rank", 0)),
            invariant_factors=tuple(invariants),
            homology_nullity=self._safe_int(result.get("homology_nullity", 0)),
            choi_kraus_rank=self._safe_int(result.get("choi_kraus_rank", 0)),
            choi_is_unital=choi_is_unital,
            choi_unital_residual=choi_unital_residual,
            choi_spectral_gap=self._safe_float(result.get("choi_spectral_gap"), 0.0),
            bell_tsirelson_margin=self._safe_float(
                result.get("bell_tsirelson_margin"),
                _TSIRELSON_LIMIT - chsh_value if math.isfinite(chsh_value) else -math.inf,
                allow_inf=True,
            ),
            engine_bell_physical=engine_bell_physical,
            engine_interlock_fired=engine_interlock,
            engine_decision_sha256=self._safe_str(result.get("decision_sha256", "")),
            engine_truth_value=self._safe_float(
                result.get("heyting_truth_value"),
                _TRUTH_VALUES[engine_verdict],
            ),
            chsh_discrepancy=float(chsh_delta) if math.isfinite(chsh_delta) else math.inf,
            operators_well_formed=observation.operators_well_formed,
            correlations_physical=observation.correlations_physical,
            agent_chsh_value=float(agent_chsh),
            interlock_consistent=bool(interlock_ok),
            snf_engine_consistent=bool(snf_ok),
            choi_hermitian_relative_residual=float(
                observation.choi_hermitian_relative_residual
            ),
        )

    def orient_audit_observation(
        self, observation: AuditObservation
    ) -> EngineAuditEvidence:
        r"""
        PRIMER MÉTODO DE LA FASE 2.

        Continuación formal de `observe_audit_event` (Fase 1).

        Consume `AuditObservation` y fiscaliza al motor físico. Si los
        operadores están mal formados, el lazo es fail-closed: se invoca
        igualmente al motor (que debe vetar) y se conserva la evidencia.
        """
        try:
            result = self._engine.execute_audit_cycle(
                boundary_matrix=observation.boundary_matrix,
                Choi_matrix=observation.Choi_matrix,
                bell_correlations=observation.bell_correlations,
            )
            if not isinstance(result, dict):
                raise TypeError("El motor de auditoría no devolvió un diccionario.")
            return self._extract_engine_evidence(result, observation)
        except Exception as exc:  # pragma: no cover - defensa ciber-física
            return self._fail_safe_evidence(observation, exc)

    def _atomic_heyting_propositions(
        self,
        evidence: EngineAuditEvidence,
        is_homology_coherent: bool,
        is_causal_coherent: bool,
        is_bell_coherent: bool,
        is_bell_classical: bool,
    ) -> List[Tuple[str, float]]:
        r"""
        Proposiciones atómicas del agente en \(\Omega_3\).

        Un átomo 0 veta; un átomo 1/2 degrada; 1 es regular. El veredicto
        del agente es el ínfimo de Gödel de esta familia.
        """
        atoms: List[Tuple[str, float]] = []
        atoms.append(
            (
                "operators",
                _OMEGA3_TRUE if evidence.operators_well_formed else _OMEGA3_FALSE,
            )
        )
        atoms.append(
            (
                "engine_valid",
                _OMEGA3_TRUE if evidence.is_valid else _OMEGA3_FALSE,
            )
        )
        atoms.append(
            ("homology", _OMEGA3_TRUE if is_homology_coherent else _OMEGA3_FALSE)
        )
        if evidence.snf_complete is False:
            atoms.append(("snf_complete", _OMEGA3_FALSE))
        else:
            atoms.append(("snf_complete", _OMEGA3_TRUE))
        atoms.append(
            (
                "snf_consistency",
                _OMEGA3_TRUE if evidence.snf_engine_consistent else _OMEGA3_FALSE,
            )
        )

        if (not math.isfinite(evidence.min_eigenvalue)) or (
            evidence.min_eigenvalue < self._choi_cp_veto_thresh
        ):
            atoms.append(("choi_cp", _OMEGA3_FALSE))
        elif evidence.min_eigenvalue < self._choi_cp_thresh:
            atoms.append(("choi_cp", _OMEGA3_MIDDLE))
        else:
            atoms.append(("choi_cp", _OMEGA3_TRUE))

        if (not math.isfinite(evidence.tp_residual)) or (
            evidence.tp_residual > self._choi_tp_veto_thresh
        ):
            atoms.append(("choi_tp", _OMEGA3_FALSE))
        elif evidence.tp_residual > self._choi_tp_thresh:
            atoms.append(("choi_tp", _OMEGA3_MIDDLE))
        else:
            atoms.append(("choi_tp", _OMEGA3_TRUE))

        if evidence.engine_is_hermitian is False:
            if (
                math.isfinite(evidence.choi_hermitian_residual)
                and evidence.choi_hermitian_residual > self._choi_herm_veto_thresh
            ):
                atoms.append(("choi_hermitian", _OMEGA3_FALSE))
            else:
                atoms.append(("choi_hermitian", _OMEGA3_MIDDLE))
        elif evidence.choi_hermitian_relative_residual > _HERMITIAN_REL_VETO:
            atoms.append(("choi_hermitian", _OMEGA3_FALSE))
        elif evidence.choi_hermitian_relative_residual > _HERMITIAN_REL_TOL:
            atoms.append(("choi_hermitian", _OMEGA3_MIDDLE))
        else:
            atoms.append(("choi_hermitian", _OMEGA3_TRUE))

        atoms.append(
            ("causal", _OMEGA3_TRUE if is_causal_coherent else _OMEGA3_MIDDLE)
        )
        atoms.append(
            ("bell_tsirelson", _OMEGA3_TRUE if is_bell_coherent else _OMEGA3_FALSE)
        )
        atoms.append(
            (
                "bell_classical",
                _OMEGA3_TRUE
                if is_bell_classical
                else (_OMEGA3_MIDDLE if is_bell_coherent else _OMEGA3_FALSE),
            )
        )
        atoms.append(
            (
                "bell_physical",
                _OMEGA3_TRUE if evidence.correlations_physical else _OMEGA3_FALSE,
            )
        )

        if (not math.isfinite(evidence.chsh_discrepancy)) or (
            evidence.chsh_discrepancy >= _CHSH_DISCREPANCY_VETO
        ):
            atoms.append(("chsh_dual", _OMEGA3_FALSE))
        elif evidence.chsh_discrepancy >= _CHSH_DISCREPANCY_DEGRADED:
            atoms.append(("chsh_dual", _OMEGA3_MIDDLE))
        else:
            atoms.append(("chsh_dual", _OMEGA3_TRUE))

        atoms.append(
            (
                "interlock",
                _OMEGA3_TRUE if evidence.interlock_consistent else _OMEGA3_FALSE,
            )
        )

        if math.isfinite(evidence.choi_trace_residual) and (
            evidence.choi_trace_residual > self._choi_tp_thresh
        ):
            atoms.append(("choi_trace", _OMEGA3_MIDDLE))
        else:
            atoms.append(("choi_trace", _OMEGA3_TRUE))

        if evidence.choi_is_unital is False:
            atoms.append(("choi_unital", _OMEGA3_MIDDLE))
        else:
            atoms.append(("choi_unital", _OMEGA3_TRUE))

        return atoms

    def prepare_agent_pre_decision(
        self, evidence: EngineAuditEvidence
    ) -> AgentPreDecision:
        r"""
        ÚLTIMO MÉTODO DE LA FASE 2.

        Consolida la evidencia del motor y emite `AgentPreDecision`.

        Dual-control intuicionista:
          - El veredicto del agente es el ínfimo de Gödel de sus átomos.
          - El veredicto final es el meet con el veredicto del motor.
          - COHERENT sólo se afirma si ambas ramas lo demuestran.

        Continúa formalmente en la Fase 3 mediante

        \[
            \texttt{act\_on\_agent\_pre\_decision}
            :
            \mathsf{AgentPreDecision}
            \longrightarrow
            \mathsf{AuditActuationReport}.
        \]
        """
        reasons: List[str] = list(evidence.engine_reasons)

        finite_min = math.isfinite(evidence.min_eigenvalue)
        finite_tp = math.isfinite(evidence.tp_residual)
        finite_chsh = math.isfinite(evidence.chsh_value)

        if not evidence.is_valid:
            reasons.append("engine_audit_invalid")
        if not finite_min:
            reasons.append("choi_min_eigenvalue_non_finite")
        if not finite_tp:
            reasons.append("choi_tp_residual_non_finite")
        if not finite_chsh:
            reasons.append("bell_chsh_non_finite")
        if not evidence.operators_well_formed:
            reasons.append("operators_ill_formed")

        is_homology_coherent = self.verify_homology_coherence(
            list(evidence.torsion_coefficients)
        )
        if evidence.engine_is_homology_coherent is False:
            is_homology_coherent = False
            reasons.append("engine_homology_not_coherent")
        if evidence.snf_complete is False:
            is_homology_coherent = False
            reasons.append("engine_snf_incomplete")
        if not is_homology_coherent:
            reasons.append("homology_torsion_detected")

        is_causal_coherent = self.verify_causal_coherence(
            evidence.min_eigenvalue,
            evidence.tp_residual,
        )
        if evidence.engine_is_causal_coherent is False:
            is_causal_coherent = False
            reasons.append("engine_causal_not_coherent")
        if evidence.engine_is_cptp is False:
            is_causal_coherent = False
            reasons.append("engine_choi_not_cptp")
        if evidence.engine_is_cp is False:
            is_causal_coherent = False
            reasons.append("engine_choi_not_cp")
        if evidence.engine_is_tp is False:
            is_causal_coherent = False
            reasons.append("engine_choi_not_tp")

        if evidence.engine_is_hermitian is False:
            if (
                math.isfinite(evidence.choi_hermitian_residual)
                and evidence.choi_hermitian_residual > self._choi_herm_veto_thresh
            ):
                reasons.append("engine_choi_hermitian_veto_residual")
            else:
                reasons.append("engine_choi_hermitian_degraded_residual")

        bell_tol = max(1.0e-12, 100.0 * _MACHINE_EPS)
        is_bell_coherent = (
            finite_chsh
            and evidence.correlations_physical
            and (evidence.chsh_value <= _TSIRELSON_LIMIT + bell_tol)
        )
        is_bell_classical = (
            finite_chsh
            and evidence.correlations_physical
            and (evidence.chsh_value <= self._bell_thresh + bell_tol)
        )
        if evidence.engine_bell_is_classical is False:
            is_bell_classical = False
            reasons.append("engine_bell_not_classical")
        if evidence.engine_bell_physical is False:
            reasons.append("engine_bell_not_physical")
        if not is_bell_coherent:
            reasons.append("bell_chsh_tsirelson_violation")
        elif not is_bell_classical:
            reasons.append("bell_chsh_above_classical_bound")
        if not evidence.interlock_consistent:
            reasons.append("engine_interlock_inconsistent_with_verdict")
        if not evidence.snf_engine_consistent:
            reasons.append("engine_snf_homology_inconsistent")
        if math.isfinite(evidence.chsh_discrepancy):
            if evidence.chsh_discrepancy >= _CHSH_DISCREPANCY_VETO:
                reasons.append("chsh_discrepancy_veto")
            elif evidence.chsh_discrepancy >= _CHSH_DISCREPANCY_DEGRADED:
                reasons.append("chsh_discrepancy_degraded")

        atoms = self._atomic_heyting_propositions(
            evidence,
            is_homology_coherent,
            is_causal_coherent,
            is_bell_coherent,
            is_bell_classical,
        )
        truth_lattice = _OMEGA3_TRUE
        for name, value in atoms:
            truth_lattice = _heyting_meet(truth_lattice, value)
            if value == _OMEGA3_FALSE:
                reasons.append(f"atom_veto:{name}")
            elif value == _OMEGA3_MIDDLE:
                reasons.append(f"atom_degraded:{name}")

        if truth_lattice == _OMEGA3_FALSE:
            agent_verdict = _VERDICT_VETOED
        elif truth_lattice == _OMEGA3_MIDDLE:
            agent_verdict = _VERDICT_DEGRADED
        else:
            agent_verdict = _VERDICT_COHERENT

        final_verdict = self._join_verdicts(evidence.engine_verdict, agent_verdict)
        if final_verdict != agent_verdict:
            reasons.append(
                f"final_verdict_joined_engine_{evidence.engine_verdict.lower()}"
            )

        margins: List[float] = []
        if finite_min:
            margins.append(
                float(
                    np.clip(
                        (evidence.min_eigenvalue - self._choi_cp_veto_thresh)
                        / max(
                            abs(self._choi_cp_thresh - self._choi_cp_veto_thresh),
                            _MACHINE_EPS,
                        ),
                        0.0,
                        1.0,
                    )
                )
            )
        else:
            margins.append(0.0)
        if finite_tp:
            margins.append(
                float(
                    np.clip(
                        1.0
                        - evidence.tp_residual
                        / max(self._choi_tp_veto_thresh, _MACHINE_EPS),
                        0.0,
                        1.0,
                    )
                )
            )
        else:
            margins.append(0.0)
        if finite_chsh:
            margins.append(
                float(
                    np.clip(
                        1.0
                        - evidence.chsh_value / max(_TSIRELSON_LIMIT, _MACHINE_EPS),
                        0.0,
                        1.0,
                    )
                )
            )
        else:
            margins.append(0.0)

        geo = _geometric_mean(margins)
        if final_verdict == _VERDICT_VETOED:
            truth_continuous = 0.0
        elif final_verdict == _VERDICT_DEGRADED:
            truth_continuous = 0.5 * geo
        else:
            truth_continuous = 0.5 + 0.5 * geo

        if not reasons:
            reasons.append("boundary_regular")

        return AgentPreDecision(
            final_verdict=final_verdict,
            agent_verdict=agent_verdict,
            engine_verdict=evidence.engine_verdict,
            truth_value=_TRUTH_VALUES[final_verdict],
            is_homology_coherent=is_homology_coherent,
            is_causal_coherent=is_causal_coherent,
            is_bell_coherent=is_bell_coherent,
            is_bell_classical=is_bell_classical,
            torsion_coefficients=evidence.torsion_coefficients,
            min_eigenvalue=evidence.min_eigenvalue,
            tp_residual=evidence.tp_residual,
            chsh_value=evidence.chsh_value,
            engine_is_cptp=evidence.engine_is_cptp,
            engine_is_cp=evidence.engine_is_cp,
            engine_is_tp=evidence.engine_is_tp,
            engine_is_hermitian=evidence.engine_is_hermitian,
            choi_trace_residual=evidence.choi_trace_residual,
            choi_hermitian_residual=evidence.choi_hermitian_residual,
            inputs_sha256=evidence.inputs_sha256,
            observation_timestamp_utc=evidence.observation_timestamp_utc,
            reasons=_unique_reasons(reasons),
            truth_continuous=float(truth_continuous),
            heyting_implies_coherent=_heyting_implies(
                _TRUTH_VALUES[final_verdict], _OMEGA3_TRUE
            ),
            atomic_propositions=tuple(atoms),
            snf_complete=evidence.snf_complete,
            invariant_factors=evidence.invariant_factors,
            choi_kraus_rank=evidence.choi_kraus_rank,
            correlations_physical=evidence.correlations_physical,
            agent_chsh_value=evidence.agent_chsh_value,
            engine_certificate_sha256=evidence.engine_decision_sha256,
            operators_well_formed=evidence.operators_well_formed,
        )


